package manager

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/oheco/oheco/internal/catalog"
)

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'"
}

func launcherScript(rel string) []byte {
	return launcherScriptWithOptions(rel, catalog.LauncherOptions{})
}

func launcherScriptWithOptions(rel string, options catalog.LauncherOptions) []byte {
	start := "#!/bin/sh\n# Generated by oo; execute the original command name.\n" +
		"oo_launcher=$(readlink -f -- \"$0\") || exit 1\n"
	if len(options.Environment) == 0 && len(options.Path) == 0 && options.Interpreter == "" && len(options.Arguments) == 0 {
		// Retain the byte-for-byte format of previously installed launchers.
		return []byte(start + "exec \"${oo_launcher%/*}/../\"" + shellQuote(rel) + " \"$@\"\n")
	}
	var script strings.Builder
	script.WriteString(start)
	script.WriteString("oo_package_root=$(CDPATH= cd -- \"${oo_launcher%/*}/..\" && pwd -P) || exit 1\n")
	var names []string
	for name := range options.Environment {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		script.WriteString("export " + name + "=\"$oo_package_root/\"" + shellQuote(options.Environment[name]) + "\n")
	}
	if len(options.Path) != 0 {
		script.WriteString("export PATH=")
		for _, path := range options.Path {
			script.WriteString("\"$oo_package_root/\"" + shellQuote(path) + ":")
		}
		script.WriteString("\"${PATH:-/usr/bin:/bin}\"\n")
	}
	script.WriteString("exec ")
	if options.Interpreter != "" {
		script.WriteString(options.Interpreter + " ")
	}
	script.WriteString("\"$oo_package_root/\"" + shellQuote(rel))
	for _, argument := range options.Arguments {
		parts := strings.Split(argument, "${PACKAGE_ROOT}")
		script.WriteString(" ")
		for i, part := range parts {
			if i != 0 {
				script.WriteString("\"$oo_package_root\"")
			}
			script.WriteString(shellQuote(part))
		}
	}
	script.WriteString(" \"$@\"\n")
	return []byte(script.String())
}

func createLaunchers(directory string, a catalog.Artifact) error {
	if len(a.Launchers) == 0 {
		return nil
	}
	dir := filepath.Join(directory, catalog.LauncherDirectory)
	// Archives cannot supply this directory, even if they declare no launchers.
	if err := os.Mkdir(dir, 0755); err != nil {
		return err
	}
	for _, name := range a.Launchers {
		filename := filepath.Join(dir, name)
		if err := os.WriteFile(filename, launcherScriptWithOptions(a.Binaries[name], a.LauncherOptions[name]), 0755); err != nil {
			return err
		}
		if err := os.Chmod(filename, 0755); err != nil {
			return err
		}
	}
	return verifyInstalled(directory, a)
}

func verifyInstalled(directory string, a catalog.Artifact) error {
	if err := verifyBinaries(directory, a); err != nil {
		return err
	}
	if len(a.Launchers) == 0 {
		return nil
	}
	dir := filepath.Join(directory, catalog.LauncherDirectory)
	info, err := os.Lstat(dir)
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("launcher directory was replaced: %s", dir)
	}
	for _, name := range a.Launchers {
		filename := filepath.Join(dir, name)
		info, err := os.Lstat(filename)
		if err != nil {
			return err
		}
		expected := launcherScriptWithOptions(a.Binaries[name], a.LauncherOptions[name])
		if !info.Mode().IsRegular() || info.Mode().Perm()&0111 == 0 || info.Size() != int64(len(expected)) {
			return fmt.Errorf("launcher was modified: %s", filename)
		}
		data, err := os.ReadFile(filename)
		if err != nil {
			return err
		}
		if !bytes.Equal(data, expected) {
			return fmt.Errorf("launcher was modified: %s", filename)
		}
	}
	return nil
}
